<h2 class="wp-block-heading bs-ui-title">Frequently Asked Questions</h2>
<!-- /wp:heading -->
<!-- wp:group {"tagName":"div","className":"bs-faq-questions bs-clean-accordion","layout":{"type":"constrained"}} -->
<div class="wp-block-group bs-faq-questions bs-clean-accordion">
<!-- wp:details -->
<details class="wp-block-details"><summary>What does a forex technology provider actually do?</summary>
<!-- wp:paragraph -->
<p>We build, connect and maintain the systems a brokerage depends on. That covers trading platforms, servers, liquidity connections, CRMs, payment and verification integrations, apps and APIs. The brokerage runs the business, and we make sure the technology underneath it works.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Are you a broker or a liquidity provider?</summary>
<!-- wp:paragraph -->
<p>Neither. We're purely a technology company. We don't execute client trades, provide liquidity, hold client money or offer investment advice.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Do I have to buy everything from you?</summary>
<!-- wp:paragraph -->
<p>No. Some clients use us for one service, such as hosting or a CRM. Others hand us the whole stack. We're happy to work alongside systems and vendors you already have.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Can you help if I don't know where to start?</summary>
<!-- wp:paragraph -->
<p>Yes, and plenty of our clients begin exactly there. During the first consultation we'll help you work out what you need, in what order and roughly what it involves.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Can you help us get a licence?</summary>
<!-- wp:paragraph -->
<p>Licensing is a legal and regulatory matter, so it's outside what we do. We can explain how technology decisions interact with common regulatory expectations, but you'll need qualified advisors in your target jurisdiction for the licence itself.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Which markets do you work with?</summary>
<!-- wp:paragraph -->
<p>We support brokerages serving clients in many regions. Where your clients are located does affect choices like hosting location, payment methods and verification providers, which we factor into the design.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Should a new broker choose MT5 or MT4?</summary>
<!-- wp:paragraph -->
<p>Most new brokers now choose MT5. It supports more asset classes, has a more modern architecture and is where the platform developer focuses ongoing work. MT4 still has a loyal user base, so some brokers offer both.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Can we run MT4 and MT5 at the same time?</summary>
<!-- wp:paragraph -->
<p>Yes. Many brokers do, either permanently or during a gradual move from one to the other. The two can share liquidity connections and a CRM.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>How hard is it to move from MT4 to MT5?</summary>
<!-- wp:paragraph -->
<p>It takes careful planning rather than heavy lifting. Account types, groups, symbols and trading conditions need recreating, integrations need reconnecting and clients need a clear transition path. Phased migrations tend to go smoothest.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Are you affiliated with the MetaTrader platform developer?</summary>
<!-- wp:paragraph -->
<p>No, not unless we state otherwise for a specific arrangement. We work with the platforms as a technology provider.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>What is an MT5 white label?</summary>
<!-- wp:paragraph -->
<p>It's an arrangement where your brokerage runs on MT5 under your own brand, inside an environment operated under an existing platform licence. You get branded access and your own account setup without buying a full server licence yourself.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Why would a broker choose white label over a full licence?</summary>
<!-- wp:paragraph -->
<p>Mainly cost and speed. A full licence carries a large upfront investment and more technical responsibility. A white label lets you launch sooner and spend less, with the option to move to your own server later.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Can I control my own spreads and account types on a white label?</summary>
<!-- wp:paragraph -->
<p>Usually, yes, within the limits of the arrangement and your liquidity setup. Exactly how much control you get varies by provider, so it's worth confirming before signing.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Does a white label give me permission to operate as a broker?</summary>
<!-- wp:paragraph -->
<p>No. It's a technology arrangement only. Financial licensing is completely separate.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>What is a grey label?</summary>
<!-- wp:paragraph -->
<p>A grey label generally sits more directly under another provider's infrastructure and arrangement, with lower entry costs and less independent control than a white label. Terms vary widely between providers, so definitions aren't always consistent.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>What's the main difference between white label and grey label?</summary>
<!-- wp:paragraph -->
<p>In broad terms, a white label gives you more control over branding and configuration, while a grey label trades some of that control for a lighter, cheaper setup. We'll explain exactly what any specific offer includes before you commit.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Is a grey label right for my business?</summary>
<!-- wp:paragraph -->
<p>It can suit smaller or early-stage operations testing the market with limited budget. If you expect fast growth or need detailed control over trading conditions, a white label or full deployment is often a better long-term fit.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Does a grey label mean I don't need a company or licence?</summary>
<!-- wp:paragraph -->
<p>Not necessarily. Requirements depend on your jurisdiction, business model and the provider's terms. Take legal advice rather than relying on general claims.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>What does a forex CRM do?</summary>
<!-- wp:paragraph -->
<p>It manages the whole client journey. Lead capture, registration, identity verification, deposits, withdrawals, trading account creation, partner commissions and reporting, usually with a client portal on top.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Can the CRM connect with MT5?</summary>
<!-- wp:paragraph -->
<p>Yes. It links to MT5 and MT4 through manager API access, so trading accounts are created, balances updated and trading data pulled in automatically.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Can it handle introducing broker commissions?</summary>
<!-- wp:paragraph -->
<p>Yes. Rebate rules are set in the CRM, which then calculates earnings from real trading data, including multi-level partner structures.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Can we move our data from our current CRM?</summary>
<!-- wp:paragraph -->
<p>In most cases, yes. We map fields between the two systems, run test imports and check records carefully before switching over.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>What is a liquidity bridge?</summary>
<!-- wp:paragraph -->
<p>It's software that sits between your trading platform and one or more liquidity providers, passing prices in and orders out. Bridges typically add tools like markups, routing rules and multi-provider pricing.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>What's the difference between a bridge, a gateway and FIX?</summary>
<!-- wp:paragraph -->
<p>A gateway is a more direct link between MT5 and an external system. A bridge is separate middleware with extra routing and aggregation features. FIX is the messaging protocol that both commonly use to communicate with providers.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Can I connect more than one liquidity provider?</summary>
<!-- wp:paragraph -->
<p>Yes. Multiple providers can be aggregated for pricing or set up as backups for each other.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Can you guarantee spreads or execution quality?</summary>
<!-- wp:paragraph -->
<p>No. Pricing and fills come from your providers and depend on market conditions. What we make sure of is that the technical link carrying them is accurate and well monitored.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Do you provide MT4 and MT5 hosting?</summary>
<!-- wp:paragraph -->
<p>Yes. We host both, along with environments where they run side by side.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Where should our trading server be?</summary>
<!-- wp:paragraph -->
<p>Typically near your main liquidity providers, with client access points closer to where your clients trade. Data rules in your markets can also influence the decision.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>What happens if a server fails?</summary>
<!-- wp:paragraph -->
<p>Your disaster recovery plan kicks in. Depending on your setup, a standby server takes over or the environment is restored from tested backups.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Can you guarantee uptime?</summary>
<!-- wp:paragraph -->
<p>No honest provider can. We reduce risk through monitoring, redundancy, tested backups and a fast response when issues arise.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Do you process client payments?</summary>
<!-- wp:paragraph -->
<p>No. Payment providers process the money. We integrate them with your CRM and trading platform so deposits and withdrawals flow properly.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Can you connect our existing payment and KYC providers?</summary>
<!-- wp:paragraph -->
<p>Usually, yes, as long as they offer usable integration options. We confirm this during the design stage.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Does your verification integration make us compliant?</summary>
<!-- wp:paragraph -->
<p>No technology can do that alone. It gives your compliance team the workflow and records they need, but compliance obligations stay with your business.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Do you build technology for prop firms?</summary>
<!-- wp:paragraph -->
<p>Yes. That includes challenge setup, automated account creation, rule monitoring, risk flags, performance dashboards and payout review workflows.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Can we have a branded mobile trading app?</summary>
<!-- wp:paragraph -->
<p>Yes. We build iOS and Android apps under your brand, connected to your platform, CRM, payments and verification. Publication is subject to app store review.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Can you integrate APIs?</summary>
<!-- wp:paragraph -->
<p>Yes. We work with manager APIs, payment and verification APIs, webhooks and custom integrations between your systems and third-party tools.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Do you offer PAMM and MAM solutions?</summary>
<!-- wp:paragraph -->
<p>Yes. We provide PAMM and MAM technology for brokers that support money managers, integrated with MT4 or MT5.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>How long does setup take?</summary>
<!-- wp:paragraph -->
<p>It depends on scope, platform choice and how quickly third-party providers complete their onboarding. You'll get a realistic timeline after the solution design stage.</p>
