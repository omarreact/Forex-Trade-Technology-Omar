<!-- /wp:paragraph -->
<!-- wp:paragraph {"className":"bs-copy"} -->
<p class="bs-copy">Commissions</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph {"className":"bs-copy"} -->
<p class="bs-copy">Commission plans can be set up per IB or per group, based on trading volume, lots, spread, fixed amounts or a combination. Calculations run automatically from trading data, so you&#039;re not rebuilding a spreadsheet every month and hoping nothing was missed. Payouts can be reviewed and approved through the same system.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph {"className":"bs-copy"} -->
<p class="bs-copy">Reporting</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph {"className":"bs-copy"} -->
<p class="bs-copy">Reports pull together CRM and trading platform data. Client acquisition by source, conversion rates, deposits and withdrawals over time, trading activity, IB performance, commission totals and verification backlogs. Management gets a clear picture of how the business is performing, and compliance gets the records it needs.</p>
