<h3 class="wp-block-heading ftt-rd-card-title">Stage 1: Acquire and Convert</h3>
<!-- /wp:heading -->
<!-- wp:paragraph {"className":"bs-copy"} -->
<p class="bs-copy">The first job is turning interest into registered, funded clients.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph {"className":"bs-copy"} -->
<p class="bs-copy">Lead Management</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph {"className":"bs-copy"} -->
<p class="bs-copy">Leads arrive from your website, landing pages, campaigns, events and IB referrals. Each one is captured automatically with its source, so you know which channels actually bring in clients rather than just traffic. Leads can be assigned to sales staff by region, language or campaign, and every call, email and note is logged against the record.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph {"className":"bs-copy"} -->
<p class="bs-copy">Your team can see where each lead stands, which ones have gone quiet and which are ready to move forward. Managers get a clear view of conversion rates by source, by team and by person.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph {"className":"bs-copy"} -->
<p class="bs-copy">Notifications</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph {"className":"bs-copy"} -->
<p class="bs-copy">Automated emails and alerts keep things moving without someone having to remember. Welcome messages after registration. Reminders when a document is still missing. Alerts to staff when a high-value lead takes action. Notifications can be set up for clients and for internal teams, so nothing important waits on someone checking their inbox.</p>
