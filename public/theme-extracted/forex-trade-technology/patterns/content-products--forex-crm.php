<p class="bs-copy">Trading Accounts</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph {"className":"bs-copy"} -->
<p class="bs-copy">Verified clients can open MT5 trading accounts through the portal, or your team can create them from the CRM. Account types, groups and leverage are applied automatically based on your rules. Account changes, such as leverage adjustments or group moves, can be requested and approved through the CRM rather than handled manually on the platform.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph {"className":"bs-copy"} -->
<p class="bs-copy">Deposits and Withdrawals</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph {"className":"bs-copy"} -->
<p class="bs-copy">Deposits from integrated payment providers are recorded in the CRM and, once confirmed, reflected in the client&#039;s trading balance. Withdrawal requests come in through the portal and move through an approval workflow your finance team controls. Checks can be built in, for example confirming verification status or reviewing recent activity before a withdrawal is released.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph {"className":"bs-copy"} -->
<p class="bs-copy">Every transaction is logged with its status and history, which makes reconciliation much simpler. Your finance team isn&#039;t comparing three systems at the end of the day to find out why numbers don&#039;t match.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph {"className":"bs-copy"} -->
<p class="bs-copy">Role-Based Access</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph {"className":"bs-copy"} -->
<p class="bs-copy">Different teams need different things. Sales should see leads and client contact details. Compliance needs documents and verification tools. Finance needs transactions and approvals. Support needs enough to help clients without seeing everything. Role-based permissions give each person access to what their job requires and nothing more, with a record of who did what.</p>
