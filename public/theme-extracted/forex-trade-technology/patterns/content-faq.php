<!-- wp:details -->
<details class="wp-block-details"><summary>What does a forex technology provider do?</summary>
<!-- wp:paragraph {"className":"bs-copy"} -->
<p class="bs-copy">A forex technology provider supplies and connects the systems a brokerage runs on. That includes trading platform setups, trading servers, liquidity connectivity, CRM, payment and KYC integrations, websites, apps and the infrastructure underneath. We&#039;re a technology company, not a broker. We don&#039;t offer trading services or investment advice, and we don&#039;t hold or manage client funds.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Do you work with new brokers or existing ones?</summary>
<!-- wp:paragraph {"className":"bs-copy"} -->
<p class="bs-copy">Both. New brokers usually need a complete setup planned and delivered in the right order. Existing brokers often come to us for a specific problem, such as a CRM that doesn&#039;t integrate properly, unstable hosting or the need for more liquidity providers.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Do I have to take your full technology stack?</summary>
<!-- wp:paragraph {"className":"bs-copy"} -->
<p class="bs-copy">No. You can take everything as a turnkey setup or just the parts you&#039;re missing. We regularly integrate with platforms, CRMs and providers that brokers already use.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Do you help with licensing or regulation?</summary>
<!-- wp:paragraph {"className":"bs-copy"} -->
<p class="bs-copy">No. We provide technology, not legal or regulatory services. Licensing requirements vary by jurisdiction, so we recommend working with qualified legal and compliance advisors. We&#039;re happy to coordinate with them on any technical requirements.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>How much does brokerage technology cost?</summary>
<!-- wp:paragraph {"className":"bs-copy"} -->
<p class="bs-copy">It depends on your platform model, integrations, number of providers and the scope of your website and portal. We don&#039;t publish fixed prices because every setup is different. After a consultation, you&#039;ll get a clear breakdown of one-off and recurring costs.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>How long does setup take?</summary>
<!-- wp:paragraph {"className":"bs-copy"} -->
<p class="bs-copy">It depends on scope and how quickly your liquidity and payment providers complete their onboarding, which can take longer than the technical work. We give you a realistic timeline after discovery rather than an optimistic estimate.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>What support do you provide after launch?</summary>
