<!-- wp:details -->
<details class="wp-block-details"><summary>Is a grey label a good way to start?</summary>
<!-- wp:paragraph {"className":"bs-copy"} -->
<p class="bs-copy">For many brokers, yes. It keeps upfront costs down and gets you to market sooner, which suits founders testing a market or working with a limited budget.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Does a grey label mean I don&#039;t need a company or licence?</summary>
<!-- wp:paragraph {"className":"bs-copy"} -->
<p class="bs-copy">No one can honestly promise that. What you need depends on your jurisdiction, business model and the provider arrangement. Get legal advice for your specific situation.</p>
