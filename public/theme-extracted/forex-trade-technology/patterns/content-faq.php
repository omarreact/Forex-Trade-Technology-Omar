<details class="wp-block-details"><summary>What is an MT5 grey label?</summary>
<!-- wp:paragraph {"className":"bs-copy"} -->
<p class="bs-copy">It&#039;s a way to run your own branded brokerage within another provider&#039;s MT5 environment. You manage your clients and brand, while the host manages the core infrastructure.</p>
