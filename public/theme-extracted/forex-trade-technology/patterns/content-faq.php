<!-- wp:details -->
<details class="wp-block-details"><summary>Can I set my own spreads on a grey label?</summary>
<!-- wp:paragraph {"className":"bs-copy"} -->
<p class="bs-copy">Usually within limits set by the host arrangement. We explain exactly what&#039;s adjustable before setup so there are no surprises.</p>
