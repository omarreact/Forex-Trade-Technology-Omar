<h2 class="wp-block-heading ftt-rd-section-title">Liquidity</h2>
<!-- /wp:heading -->
<!-- wp:group {"className":"bs-faq-accordion ftt-rd-accordion"} -->
<div class="wp-block-group bs-faq-accordion ftt-rd-accordion">
<!-- wp:details -->
<details class="wp-block-details"><summary>What is a liquidity bridge?</summary>
<!-- wp:paragraph {"className":"bs-copy"} -->
<p class="bs-copy">A liquidity bridge is software that connects your trading platform to liquidity providers. It brings prices into the platform, routes client orders according to your rules and processes execution reports.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Are you a liquidity provider?</summary>
<!-- wp:paragraph {"className":"bs-copy"} -->
<p class="bs-copy">No. We build and maintain the technology that connects your platform to the liquidity providers you choose.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>What&#039;s the difference between a bridge and FIX API?</summary>
<!-- wp:paragraph {"className":"bs-copy"} -->
<p class="bs-copy">A bridge is software that manages connectivity and routing between your platform and providers. FIX API is a standard messaging protocol that can be used for direct connections. Many setups use both.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Can I connect more than one liquidity provider?</summary>
<!-- wp:paragraph {"className":"bs-copy"} -->
<p class="bs-copy">Yes. Multiple providers with aggregation or backup routing is a common setup, and it reduces dependence on any single provider.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Can you set up A-book, B-book or hybrid routing?</summary>
<!-- wp:paragraph {"className":"bs-copy"} -->
<p class="bs-copy">Yes. We configure routing to match your chosen execution model. The model and risk policy themselves are your decisions.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Do you guarantee spreads or execution?</summary>
<!-- wp:paragraph {"className":"bs-copy"} -->
<p class="bs-copy">No. Pricing and execution depend on your providers and market conditions. We make sure the technology connecting you to them is configured and maintained properly.</p>
<!-- /wp:paragraph -->
</details>
