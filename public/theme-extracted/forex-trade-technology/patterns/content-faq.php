<h2 class="wp-block-heading ftt-rd-section-title">White Label</h2>
<!-- /wp:heading -->
<!-- wp:group {"className":"bs-faq-accordion ftt-rd-accordion"} -->
<div class="wp-block-group bs-faq-accordion ftt-rd-accordion">
<!-- wp:details -->
<details class="wp-block-details"><summary>What is MT5 white label?</summary>
<!-- wp:paragraph {"className":"bs-copy"} -->
<p class="bs-copy">An MT5 white label is a branded MetaTrader 5 environment set up for your brokerage. Clients trade on a platform carrying your name, and you generally have greater control over trading groups, account types, symbols and trading conditions than you would with a grey label.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>What is a forex white label?</summary>
<!-- wp:paragraph {"className":"bs-copy"} -->
<p class="bs-copy">A forex white label is a complete brokerage technology foundation branded as your own. Alongside the trading platform, it typically includes a CRM, liquidity connectivity, hosting, a website, client portal, payments and KYC tools.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Who should choose a white label?</summary>
<!-- wp:paragraph {"className":"bs-copy"} -->
<p class="bs-copy">Brokers with clear growth plans who want control over their platform setup, expect meaningful trading volumes or plan to expand into new products and regions.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Does a white label include a broker licence?</summary>
<!-- wp:paragraph {"className":"bs-copy"} -->
<p class="bs-copy">No. A white label is a technology arrangement. Licensing and regulatory approval are separate and depend on your jurisdiction.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Should I choose MT5 or MT4?</summary>
<!-- wp:paragraph {"className":"bs-copy"} -->
<p class="bs-copy">Most new brokers choose MT5 for its multi-asset support and because it&#039;s the platform MetaQuotes actively develops. MT4 still makes sense if your target clients specifically rely on it, for example experienced forex traders using MQL4 Expert Advisors.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Can I move from MT4 to MT5 later?</summary>
<!-- wp:paragraph {"className":"bs-copy"} -->
<p class="bs-copy">Yes. We can plan a gradual or full migration, and many brokers run both platforms side by side during the transition.</p>
