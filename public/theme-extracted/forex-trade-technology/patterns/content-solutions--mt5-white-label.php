<h2 class="wp-block-heading ftt-rd-section-title">What Is an MT5 White Label?</h2>
<!-- /wp:heading -->
<!-- wp:paragraph {"className":"bs-copy"} -->
<p class="bs-copy">A MetaTrader 5 white label is a branded instance of the MT5 platform set up for your brokerage. Your clients download a terminal that carries your name. Your team manages accounts, groups and trading conditions through administration tools. The core platform technology is developed by MetaQuotes, and the setup, hosting and day-to-day technical management are handled by your technology partner.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph {"className":"bs-copy"} -->
<p class="bs-copy">The key word is control. With a white label, you generally have far more say over how the trading environment is configured than you would under a grey label. You decide how account types are structured, how symbols are set up, what leverage and margin rules apply to each group, and how orders are handled. As your business changes, you can change those settings with it.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph {"className":"bs-copy"} -->
<p class="bs-copy">It&#039;s worth being clear about what an MT5 white label solution is not. It isn&#039;t a financial licence, and it doesn&#039;t give you permission to operate as a broker in any particular country. Licensing is a separate process, and the requirements vary by jurisdiction. The white label is the technology. The regulatory side is something you&#039;ll handle with qualified legal and compliance advisors.</p>
