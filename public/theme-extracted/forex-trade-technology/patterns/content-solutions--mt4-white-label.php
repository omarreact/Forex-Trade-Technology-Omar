<!-- /wp:paragraph -->
<!-- wp:paragraph {"className":"bs-copy"} -->
<p class="bs-copy">Your MT4 trading server holds your groups, symbols, trading conditions and client accounts. It&#039;s hosted on monitored infrastructure with backups in place.</p>
